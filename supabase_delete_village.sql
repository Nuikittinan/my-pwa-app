-- ==========================================================
-- ลบหมู่บ้านทิ้ง พร้อมข้อมูลที่เกี่ยวข้องทั้งหมด (บ้าน/บิล/แอดมิน/ตั้งค่า)
-- แก้ 'ชื่อหมู่บ้านที่จะลบ' ให้ตรงกับชื่อจริง แล้วรันทีละคำสั่งตามลำดับนี้
-- (ต้องลบตามลำดับนี้ ห้ามสลับ เพราะมี foreign key อ้างอิงกันอยู่)
-- ==========================================================

-- 1) หา village_id ก่อน (รันดูผลลัพธ์นี้ก่อน เพื่อคัดลอก id ไปใช้ต่อ)
select id, name from villages where name = 'ชื่อหมู่บ้านที่จะลบ';

-- 2) ลบบิลทั้งหมดของหมู่บ้านนี้
delete from bills where village_id = 'วาง_village_id_ตรงนี้';

-- 3) ลบบ้านทั้งหมดของหมู่บ้านนี้
delete from houses where village_id = 'วาง_village_id_ตรงนี้';

-- 4) ลบแอดมินทั้งหมดของหมู่บ้านนี้
delete from admins where village_id = 'วาง_village_id_ตรงนี้';

-- 5) ลบการตั้งค่าของหมู่บ้านนี้
delete from settings where village_id = 'วาง_village_id_ตรงนี้';

-- 6) สุดท้ายค่อยลบตัวหมู่บ้านเอง
delete from villages where id = 'วาง_village_id_ตรงนี้';
