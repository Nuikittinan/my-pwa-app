-- ==========================================================
-- เพิ่ม policy ให้สมัครหมู่บ้านใหม่ผ่านแอปได้ (ไม่ต้องเข้า Supabase เอง)
-- รันต่อจาก supabase_migration_multitenant.sql
-- ==========================================================

-- villages: ตอนแรกเปิดแค่ "อ่านได้" (สำหรับ dropdown หน้า login)
-- ตอนนี้เปิดให้ "สร้างหมู่บ้านใหม่" ได้ด้วย (สมัครเอง) แต่ยังห้ามแก้ไข/ลบจาก frontend
create policy "public write villages" on villages for insert with check (true);

-- admins: เดิมมีแค่ "อ่านได้" (ใช้ตอน login) ตอนนี้ต้องสร้างแอดมินคนแรกของหมู่บ้านใหม่ได้ด้วย
create policy "public write admins" on admins for insert with check (true);

-- settings: เดิมมีแค่ "อ่านได้" กับ "แก้ไขได้" ตอนนี้ต้องสร้างแถวตั้งต้นของหมู่บ้านใหม่ได้ด้วย
create policy "public write settings" on settings for insert with check (true);

-- ⚠️ หมายเหตุ: ใครก็ตามที่เปิดเว็บเจอ (มี anon key) จะสมัครหมู่บ้านใหม่ได้ไม่จำกัดจำนวน
-- เหมาะกับช่วงทดลองใช้งานภายใน ถ้าจะเปิดสาธารณะจริงจัง ควรเพิ่มการยืนยันตัวตน
-- (เช่น ยืนยันเบอร์โทร/อีเมล) ก่อนอนุญาตให้สร้างหมู่บ้านในอนาคต
