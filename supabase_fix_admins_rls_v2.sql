-- 1) บังคับให้ Supabase (PostgREST) โหลด policy/schema ใหม่
-- (บางครั้งแก้ policy แล้วแอปยังเห็นของเก่าค้างอยู่สักพัก คำสั่งนี้เคลียร์ cache ทันที)
notify pgrst, 'reload schema';

-- ลองกลับไปกดสมัครหมู่บ้านใหม่ที่แอปตอนนี้เลย ถ้ายัง error เหมือนเดิม ให้รันต่อข้อ 2

-- 2) เช็คว่า helper function ทำงานถูกต้องไหม (เรียกจาก SQL Editor จะได้ NULL เสมอ
-- เพราะไม่มี JWT context ก็จริง แต่อย่างน้อยต้องไม่ error ว่าฟังก์ชันไม่มีอยู่)
select public.current_role(), public.current_village_id();

-- ถ้าคำสั่งนี้ error (ไม่ใช่แค่ขึ้น NULL) ให้คัดลอกข้อความ error เต็มๆ มาให้ดู

-- 3) ถ้าข้อ 1 ไม่ช่วย ให้ลองเปิด policy แบบเปิดกว้างชั่วคราว เพื่อเช็คว่าเป็นที่ตัว
-- เงื่อนไข with check จริงๆ หรือเป็นปัญหาอื่น (รันคำสั่งนี้แล้วลองสมัครหมู่บ้านใหม่อีกที)
drop policy if exists "insert admin (first admin or by existing full admin)" on admins;
create policy "insert admin (first admin or by existing full admin)" on admins
  for insert with check (true);

-- ถ้าสมัครผ่านตอนนี้ -> ยืนยันว่าปัญหาอยู่ที่เงื่อนไขเดิม บอกผลมาแล้วผมจะแก้เงื่อนไขให้ใหม่
-- ถ้ายัง error เหมือนเดิมแม้เปิดกว้างสุดแล้ว -> ปัญหาไม่ได้อยู่ที่ policy นี้ อาจเป็นตารางอื่น
